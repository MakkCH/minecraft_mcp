import { mkdirSync, copyFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
mkdirSync(`${root}build/classes`, {recursive:true});
mkdirSync(`${root}dist`, {recursive:true});
execFileSync('javac', ['--release','21','-d',`${root}build/classes`,`${root}bridge/src/minecraft/mcp/Bridge.java`], {stdio:'inherit'});
execFileSync('jar', ['--create','--file',`${root}dist/minecraft-mcp-bridge.jar`,'-C',`${root}build/classes`,'.'], {stdio:'inherit'});
copyFileSync(`${root}client/bootstrap.js`, `${root}dist/bootstrap.js`);
console.log('Built dist/minecraft-mcp-bridge.jar and bootstrap.js');
